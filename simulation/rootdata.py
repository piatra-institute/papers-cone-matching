"""Exact root-system data: Cartan matrices, positive roots, heights and the vectors n, m, kappa.

Convention: C[i][j] = <alpha_i, alpha_j^vee>. rho = sum_i n_i alpha_i and rho^vee = sum_i m_i alpha_i^vee are
half-sums of positive roots and coroots, so <rho, alpha_j^vee> = <alpha_j, rho^vee> = 1 for every simple j.
All arithmetic uses fractions.Fraction.
"""
from __future__ import annotations

from fractions import Fraction as F
from itertools import combinations_with_replacement


def _chain(n, a=-1, b=-1):
    c = [[0] * n for _ in range(n)]
    for i in range(n):
        c[i][i] = 2
    for i in range(n - 1):
        c[i][i + 1] = a
        c[i + 1][i] = b
    return c


def cartan(kind: str, rank: int):
    """Cartan matrix C[i][j] = <alpha_i, alpha_j^vee> of an irreducible reduced root system."""
    if kind == "A":
        return _chain(rank)
    if kind == "B":  # alpha_rank short
        c = _chain(rank)
        c[rank - 2][rank - 1] = -2
        return c
    if kind == "C":  # alpha_rank long
        c = _chain(rank)
        c[rank - 1][rank - 2] = -2
        return c
    if kind == "D":
        c = [[0] * rank for _ in range(rank)]
        for i in range(rank):
            c[i][i] = 2
        for i in range(rank - 2):
            c[i][i + 1] = c[i + 1][i] = -1
        c[rank - 3][rank - 1] = c[rank - 1][rank - 3] = -1
        return c
    if kind == "E":
        # Bourbaki labelling: 1-3-4-5-6(-7-8) with 2 attached to 4
        edges = [(1, 3), (3, 4), (4, 5), (5, 6), (2, 4)] + ([(6, 7)] if rank >= 7 else []) + ([(7, 8)] if rank == 8 else [])
        c = [[0] * rank for _ in range(rank)]
        for i in range(rank):
            c[i][i] = 2
        for a, b in edges:
            c[a - 1][b - 1] = c[b - 1][a - 1] = -1
        return c
    if kind == "F":
        c = _chain(4)
        c[1][2] = -2  # alpha_1, alpha_2 long; alpha_3, alpha_4 short
        return c
    if kind == "G":
        return [[2, -1], [-3, 2]]  # alpha_1 short, alpha_2 long
    raise ValueError(kind)


def block(*mats):
    r = sum(len(m) for m in mats)
    c = [[0] * r for _ in range(r)]
    o = 0
    for m in mats:
        for i in range(len(m)):
            for j in range(len(m)):
                c[o + i][o + j] = m[i][j]
        o += len(m)
    return c


def inverse(c):
    """Exact inverse of a square integer matrix (Gauss-Jordan over Q)."""
    r = len(c)
    a = [[F(c[i][j]) for j in range(r)] + [F(int(i == j)) for j in range(r)] for i in range(r)]
    for col in range(r):
        piv = next(i for i in range(col, r) if a[i][col] != 0)
        a[col], a[piv] = a[piv], a[col]
        p = a[col][col]
        a[col] = [x / p for x in a[col]]
        for i in range(r):
            if i != col and a[i][col] != 0:
                f = a[i][col]
                a[i] = [x - f * y for x, y in zip(a[i], a[col])]
    return [row[r:] for row in a]


def transpose(c):
    return [list(x) for x in zip(*c)]


def positive_roots(c):
    """Positive roots in simple-root coordinates, generated by simple reflections."""
    r = len(c)
    simple = [tuple(int(i == j) for j in range(r)) for i in range(r)]
    roots = set(simple)
    frontier = list(simple)
    while frontier:
        new = []
        for b in frontier:
            for i in range(r):
                pair = sum(b[k] * c[k][i] for k in range(r))  # <beta, alpha_i^vee>
                s = tuple(b[k] - (pair if k == i else 0) for k in range(r))
                if s not in roots:
                    roots.add(s)
                    new.append(s)
        frontier = new
    return sorted(x for x in roots if all(v >= 0 for v in x))


def data(c):
    """Return dict with n, m, kappa, M=(C^T)^{-1}, heights H and consistency checks."""
    r = len(c)
    cinv = inverse(c)
    M = inverse(transpose(c))
    n = [sum(M[i][j] for j in range(r)) for i in range(r)]
    m = [sum(cinv[i][j] for j in range(r)) for i in range(r)]
    pos = positive_roots(c)
    copos = positive_roots(transpose(c))
    H = sum(sum(b) for b in pos)
    n_from_roots = [F(sum(b[i] for b in pos), 2) for i in range(r)]
    m_from_coroots = [F(sum(b[i] for b in copos), 2) for i in range(r)]
    kappa = sum(n)
    return {
        "rank": r, "C": c, "M": M, "n": n, "m": m, "kappa": kappa, "H": H,
        "n_positive_roots": len(pos),
        "check_n": n == n_from_roots, "check_m": m == m_from_coroots,
        "check_kappa": kappa == sum(m) and 2 * kappa == H,
    }


IRREDUCIBLE = ([("A", k) for k in range(1, 9)] + [("B", k) for k in range(2, 9)] + [("C", k) for k in range(3, 9)]
               + [("D", k) for k in range(4, 9)] + [("E", 6), ("E", 7), ("E", 8), ("F", 4), ("G", 2)])


def name(components):
    out = []
    for comp in sorted(set(components)):
        k = components.count(comp)
        out.append(f"{comp[0]}{comp[1]}" + (f"^{k}" if k > 1 else ""))
    return "+".join(out)


def products(max_rank: int):
    """All semisimple types (multisets of irreducible components) with total rank <= max_rank."""
    comps = [x for x in IRREDUCIBLE if x[1] <= max_rank]
    out = []
    for k in range(1, max_rank + 1):
        for combo in combinations_with_replacement(comps, k):
            if sum(x[1] for x in combo) <= max_rank:
                out.append(list(combo))
    return out


def cartan_of(components):
    return block(*[cartan(*x) for x in components])
